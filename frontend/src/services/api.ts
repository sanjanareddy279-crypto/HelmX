import type {
  DetectionResult,
  DetectionRecord,
  Statistics,
  HealthStatus,
} from '@/types';

const BACKEND_URL =
  import.meta.env.VITE_API_URL || 'http://localhost:8000';

interface BackendDetection {
  class: string;
  confidence: number;
  box: [number, number, number, number];
}

interface BackendImageResponse {
  filename: string;
  detections: BackendDetection[];
  count: number;
  summary?: string;
  result_image?: string;
}

export async function checkHealth(): Promise<HealthStatus> {
  try {
    const res = await fetch(`${BACKEND_URL}/health`, {
      signal: AbortSignal.timeout(5000),
    });

    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }

    const data = await res.json();

    return {
      api: 'online',
      model: data.model_loaded ? 'online' : 'offline',
      modelLoaded: data.model_loaded ?? false,
      version: data.version ?? 'unknown',
    };
  } catch {
    return {
      api: 'offline',
      model: 'offline',
      modelLoaded: false,
      version: '—',
    };
  }
}

export async function analyzeImage(
  file: File,
  threshold: number = 0.5
): Promise<DetectionResult> {
  const formData = new FormData();

  formData.append('file', file);
  formData.append('threshold', String(threshold));

  const res = await fetch(`${BACKEND_URL}/predict/image`, {
    method: 'POST',
    body: formData,
  });

  if (!res.ok) {
    throw new Error(`Detection failed: HTTP ${res.status}`);
  }

  const data: BackendImageResponse = await res.json();

  // Count helmet and no-helmet detections
  const helmetCount = data.detections.filter(
    (detection) => detection.class.toLowerCase() === 'helmet'
  ).length;

  const noHelmetCount = data.detections.filter(
    (detection) =>
      detection.class.toLowerCase() === 'no_helmet' ||
      detection.class.toLowerCase() === 'no helmet'
  ).length;

  // Calculate average confidence
  const confidence =
    data.detections.length > 0
      ? data.detections.reduce(
          (total, detection) => total + detection.confidence,
          0
        ) / data.detections.length
      : 0;

  // A violation exists if at least one person is detected without a helmet
  const violations = noHelmetCount > 0;

  // Convert backend [x1, y1, x2, y2]
  // into frontend { x, y, width, height }
  const boxes = data.detections.map((detection) => {
    const [x1, y1, x2, y2] = detection.box;

    return {
      x: x1,
      y: y1,
      width: x2 - x1,
      height: y2 - y1,
      label: detection.class,
      confidence: detection.confidence,
    };
  });

  // URL for annotated image generated by FastAPI
  const annotatedUrl = data.result_image
    ? `${BACKEND_URL}/results/${data.result_image}`
    : undefined;

  return {
    helmetCount,
    noHelmetCount,
    confidence,
    violations,
    boxes,
    annotatedUrl,
  };
}

export async function analyzeVideo(
  file: File,
  threshold: number = 0.5
): Promise<DetectionResult> {
  const formData = new FormData();

  formData.append('file', file);
  formData.append('threshold', String(threshold));

  const res = await fetch(`${BACKEND_URL}/detect/video`, {
    method: 'POST',
    body: formData,
  });

  if (!res.ok) {
    throw new Error(`Detection failed: HTTP ${res.status}`);
  }

  return res.json();
}

export async function getStatistics(): Promise<Statistics> {
  const res = await fetch(`${BACKEND_URL}/api/statistics`);

  if (!res.ok) {
    throw new Error(`HTTP ${res.status}`);
  }

  return res.json();
}

export async function getDetectionHistory(): Promise<DetectionRecord[]> {
  const res = await fetch(`${BACKEND_URL}/api/history`);

  if (!res.ok) {
    throw new Error(`HTTP ${res.status}`);
  }

  return res.json();
}